"""Exercise the in-process telemetry API and record actual status responses."""

from __future__ import annotations

import asyncio
from datetime import datetime, timedelta, timezone
import json
from pathlib import Path
import secrets
import sys
from unittest.mock import patch

from httpx import ASGITransport, AsyncClient

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from app.config import settings  # noqa: E402
from app.ingestion.device_auth import clear_replay_cache, sign_telemetry_payload  # noqa: E402
from app.ingestion.source_tracker import telemetry_source_tracker  # noqa: E402
from app.main import app  # noqa: E402


DEVICE_KEY = "e2e-device-secret-0123456789abcdef"


async def main() -> None:
    original_keys = settings.hardware_device_keys
    original_freshness = telemetry_source_tracker.freshness
    settings.hardware_device_keys = {"N01": DEVICE_KEY}
    telemetry_source_tracker.freshness = timedelta(seconds=1)
    telemetry_source_tracker.clear()
    clear_replay_cache()

    reading = {
        "node_id": "N01",
        "zone_id": "Z01",
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "accel_x": 0.18,
        "accel_y": 0.14,
        "accel_z": 9.78,
        "tilt_x": 1.2,
        "tilt_y": 0.8,
        "vibration": 0,
    }

    try:
        with (
            patch("app.api.routes.telemetry.save_reading_safe", return_value=True),
            patch("app.api.routes.telemetry.pipeline.process_reading", return_value=None),
            patch("app.api.routes.health.check_db_connection", return_value=False),
        ):
            async with AsyncClient(
                transport=ASGITransport(app=app),
                base_url="http://test",
            ) as client:
                transitions = []

                async def record(label: str) -> dict:
                    status_response = await client.get("/api/system/status")
                    status_response.raise_for_status()
                    state = status_response.json()
                    transitions.append({"step": label, "status": state})
                    return state

                await record("initial")
                simulator_response = await client.post(
                    "/api/telemetry",
                    json={**reading, "source": "simulator"},
                )
                simulator_response.raise_for_status()
                assert (await record("after simulator telemetry"))["mode"] == "SIMULATED"

                signed = {
                    **reading,
                    "source": "hardware",
                    "timestamp": datetime.now(timezone.utc).isoformat(),
                    "nonce": secrets.token_hex(16),
                }
                signed["signature"] = sign_telemetry_payload(signed, DEVICE_KEY)
                hardware_response = await client.post("/api/telemetry", json=signed)
                hardware_response.raise_for_status()
                assert (
                    await record("after valid signed hardware telemetry")
                )["mode"] == "LIVE"

                await asyncio.sleep(1.05)
                assert (
                    await record("after telemetry freshness expires")
                )["mode"] == "OFFLINE"

        output = {
            "environment": "in-process FastAPI ASGITransport; database save and processing stubbed",
            "transitions": transitions,
            "telemetry_post_status_codes": {
                "simulator": simulator_response.status_code,
                "signed_hardware": hardware_response.status_code,
            },
            "docker_mqtt_chain": "NOT RUN",
        }
        rendered = (
            "# In-process telemetry status run\n\n"
            "Generated by `scripts/run_e2e_inprocess.py`. This run exercises the "
            "FastAPI telemetry and status routes in-process; database persistence "
            "and detector processing are stubbed. The Docker/MQTT chain was NOT RUN.\n\n"
            "Actual response data:\n\n```json\n"
            f"{json.dumps(output, indent=2)}\n"
            "```\n"
        )
        report_path = ROOT / "docs" / "evaluation" / "e2e_run.md"
        report_path.write_text(rendered, encoding="utf-8", newline="\n")
        print(rendered, end="")
    finally:
        telemetry_source_tracker.clear()
        telemetry_source_tracker.freshness = original_freshness
        settings.hardware_device_keys = original_keys
        clear_replay_cache()


if __name__ == "__main__":
    asyncio.run(main())
